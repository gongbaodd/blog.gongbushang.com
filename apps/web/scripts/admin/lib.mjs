// Pure helpers for scripts/admin/start.mjs (D12, INF-7). No side effects, so they can be unit tested.
import { parseEnv } from "node:util";

export const LOCAL_DB_URL = "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
export const GENERATED_HEADER = "# GENERATED by apps/web/scripts/admin/start.mjs. Do not edit, do not commit. Removed on exit.";

/** Per-env settings. Variable names only; values come from the repo-root .env (or .dev.vars for local). */
export const ENVS = {
	local: {
		cloudflareEnv: "admin-local",
		siteEnv: "local",
		urlVar: "SUPABASE_LOCAL_DB_URL", // optional: defaults to LOCAL_DB_URL
		defaultUrl: LOCAL_DB_URL,
		keyVars: ["EMDASH_LOCAL_ENCRYPTION_KEY"], // optional: falls back to EMDASH_ENCRYPTION_KEY in apps/web/.dev.vars
		keyOptional: true,
		allowFakeGithub: true,
	},
	production: {
		cloudflareEnv: "admin-production",
		siteEnv: "production",
		urlVar: "SUPABASE_PRODUCTION_POOLER_URL",
		keyVars: ["EMDASH_PRODUCTION_ENCRYPTION_KEY"],
		allowFakeGithub: false,
	},
};

/** Non-DB secrets copied through from .dev.vars (read only) and .env, in that order (.env wins). */
export const PASSTHROUGH = [
	"CLOUDINARY_CLOUD_NAME",
	"CLOUDINARY_API_KEY",
	"CLOUDINARY_API_SECRET",
	"GITHUB_DISPATCH_TOKEN",
	"GITHUB_DISPATCH_REPO",
];

export function parseEnvText(text) {
	return text ? parseEnv(text) : {};
}

/** Hostname (never credentials) of a postgres URL, for display. */
export function dbHost(url) {
	try {
		const u = new URL(url);
		return `${u.hostname}:${u.port || "5432"}${u.pathname}`;
	} catch {
		return "<unparseable url>";
	}
}

export function looksLikePostgresUrl(url) {
	return /^postgres(ql)?:\/\/[^\s]+$/.test(url ?? "");
}

/**
 * Resolve the DB URL and encryption key for an env.
 * Returns `{ ok: true, url, key }` or `{ ok: false, missing: [varNames] }`. Never generates secrets.
 */
export function resolveEnv(envName, dotEnv, devVars) {
	const cfg = ENVS[envName];
	if (!cfg) return { ok: false, missing: [], error: `unknown env "${envName}" (expected local or production; testing was retired by INF-10)` };
	const missing = [];
	let url = dotEnv[cfg.urlVar] || cfg.defaultUrl;
	if (!url) missing.push(cfg.urlVar);
	else if (!looksLikePostgresUrl(url)) return { ok: false, missing: [], error: `${cfg.urlVar} is not a postgres:// URL` };
	let key = cfg.keyVars.map((v) => dotEnv[v]).find(Boolean);
	if (!key && cfg.keyOptional) key = devVars.EMDASH_ENCRYPTION_KEY;
	if (!key && !cfg.keyOptional) missing.push(...cfg.keyVars);
	if (missing.length) return { ok: false, missing };
	return { ok: true, url, key };
}

/** Add an application_name so the probe can recognise this server's connections in pg_stat_activity. */
export function withAppName(url, appName) {
	const u = new URL(url);
	u.searchParams.set("application_name", appName);
	return u.toString();
}

/** Contents of the generated `.dev.vars.<cloudflareEnv>`: forced values first, then passthrough secrets. */
export function buildDevVars(envName, { url, key }, dotEnv, devVars) {
	const cfg = ENVS[envName];
	const out = {
		CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE: url,
		...(key ? { EMDASH_ENCRYPTION_KEY: key } : {}), // optional for local only (encrypted plugin settings are unavailable)
		SITE_ENV: cfg.siteEnv,
	};
	for (const name of PASSTHROUGH) {
		const v = dotEnv[name] || devVars[name];
		if (v) out[name] = v;
	}
	// A fake/local GitHub API (used to test dispatch) is only honoured locally: production must hit real GitHub.
	if (cfg.allowFakeGithub) {
		const v = dotEnv.GITHUB_API_URL || devVars.GITHUB_API_URL;
		if (v) out.GITHUB_API_URL = v;
	}
	return out;
}

export function serializeDevVars(vars) {
	const lines = Object.entries(vars).map(([k, v]) => `${k}=${JSON.stringify(String(v))}`);
	return `${GENERATED_HEADER}\n${lines.join("\n")}\n`;
}

/** Replace secret values and postgres URLs in text. `secrets` may include short strings: only values >= 8 chars are matched. */
export function redact(text, secrets) {
	let out = String(text).replace(/postgres(ql)?:\/\/[^\s"'<>]+/g, "postgres://<redacted>");
	for (const s of secrets) {
		if (typeof s === "string" && s.length >= 8) out = out.split(s).join("<redacted>");
	}
	return out;
}

/**
 * Browser URL for the admin (SEC-07). Always `localhost`, never `127.0.0.1`: WebAuthn rejects IP literals as RP IDs and treats
 * `localhost` and `127.0.0.1` as different origins, so a passkey registered on one never works on the other.
 */
export function adminBrowserUrl(port) {
	return `http://localhost:${port}`;
}

export const DOCKER_ADMIN_HINT =
	"Use the Docker admin instead (production Node build: no dev-bypass, SETUP_TOKEN gate, Cloudflare Access): " +
	"docs/plan/emdash/runbooks/admin-docker.md (cd apps/admin && docker compose up).";

/**
 * SEC-07: `admin:production` runs `astro dev` against the LIVE database. In dev mode EmDash exposes
 * `/_emdash/api/auth/dev-bypass` (an admin session with no passkey) and the SETUP_TOKEN gate is off, so any local process or a
 * DNS-rebinding page reaching the port is an admin. The launcher is deprecated for production: it refuses unless BOTH
 * `--yes-production` and `--unsafe-dev-server` are passed, and then returns a loud warning to print.
 * Returns { ok: true, warning? } or { ok: false, message, code }.
 */
export function productionLaunchGate(envName, flags) {
	if (envName !== "production") return { ok: true };
	const has = (f) => flags.includes(f);
	if (!has("yes-production")) {
		return {
			ok: false,
			code: 2,
			message:
				"`pnpm admin:production` is DEPRECATED (SEC-07): it runs `astro dev` against the LIVE production database.\n" +
				`         ${DOCKER_ADMIN_HINT}`,
		};
	}
	if (!has("unsafe-dev-server")) {
		return {
			ok: false,
			code: 2,
			message:
				"refusing to run `astro dev` against the LIVE production database (SEC-07): dev mode exposes " +
				"/_emdash/api/auth/dev-bypass (an admin session without a passkey) and turns the SETUP_TOKEN gate off.\n" +
				`         ${DOCKER_ADMIN_HINT}\n` +
				"         Emergency only: pnpm admin:production -- --yes-production --unsafe-dev-server, then pnpm admin:stop as soon as you are done.",
		};
	}
	return {
		ok: true,
		warning:
			"WARNING (SEC-07): astro dev against PRODUCTION. /_emdash/api/auth/dev-bypass is reachable by anything that can reach this " +
			"port. Do not browse untrusted sites meanwhile, and run `pnpm admin:stop` as soon as you are done.",
	};
}
